    [Fact]
    public async Task CreateAndRunBenchmarkAsync_ShouldPreferAutoGeneratedQaPairs()
    {
        var courseId = 1;
        var autoGeneratedQAs = new List<QAPair>
        {
            new()
            {
                Id = 1,
                CourseId = courseId,
                DocumentChunkId = 10,
                Question = "AI generated question?",
                Answer = "AI generated answer"
            }
        };
        var documents = new List<Document> { new() { Id = 5, CourseId = courseId } };
        var chunks = new List<DocumentChunk>
        {
            new()
            {
                Id = 10,
                DocumentId = 5,
                Content = "AI generated answer",
                Embeddings =
                {
                    new ChunkEmbedding
                    {
                        EmbeddingModelName = "multilingual-e5-base",
                        EmbeddingVector = "[1,0,0]"
                    }
                }
            }
        };

        _qaPairRepositoryMock.Setup(r => r.GetQueryable())
            .Returns(autoGeneratedQAs.AsAsyncQueryable());
        _embeddingModelRepositoryMock.Setup(r => r.GetByIdAsync(1))
            .ReturnsAsync(new EmbeddingModel { Id = 1, Name = "multilingual-e5-base" });
        _documentRepositoryMock.Setup(r => r.GetByCourseIdAsync(courseId))
            .ReturnsAsync(documents);
        _chunkRepositoryMock.Setup(r => r.GetChunksWithEmbeddingsByDocumentIdsAsync(It.IsAny<IList<int>>()))
            .ReturnsAsync(chunks);
        _embeddingServiceMock.Setup(s => s.GenerateEmbeddingAsync(It.IsAny<string>()))
            .ReturnsAsync(new[] { 1f, 0f, 0f });
        _llmServiceMock.Setup(s => s.GenerateAnswerAsync(It.IsAny<string>(), It.IsAny<string>()))
            .ReturnsAsync("AI generated answer");

        var service = CreateService();

        var runId = await service.CreateAndRunBenchmarkAsync(new CreateBenchmarkRunDto
        {
            Name = "Document-grounded test set",
            EmbeddingModelId = 1,
            ChunkingStrategy = "FixedSize",
            ChunkSize = 512,
            ChunkOverlap = 50
        }, courseId);

        runId.Should().Be(0);
        _documentRepositoryMock.Verify(r => r.GetByCourseIdAsync(courseId), Times.Once);
        _resultRepositoryMock.Verify(r => r.AddAsync(It.Is<BenchmarkResult>(result =>
            result.Question == "AI generated question?" &&
            result.GroundTruth == "AI generated answer")), Times.Once);
    }


        {
            new()
            {
                Id = 1,
                CourseId = courseId,
                DocumentChunkId = 10,
                Question = "What is Start()?",
                Answer = "It starts listening for incoming connections."
            }
        };
        var documents = new List<Document> { new() { Id = 5, CourseId = courseId } };
        var chunks = new List<DocumentChunk>
        {
            new()
            {
                Id = 10,
                DocumentId = 5,
                Content = "It starts listening for incoming connections.",
                Embeddings =
                {
                    new ChunkEmbedding
                    {
                        EmbeddingModelName = "multilingual-e5-base",
                        EmbeddingVector = "[1,0,0]"
                    }
                }
            }
        };

        _qaPairRepositoryMock.Setup(r => r.GetQueryable())
            .Returns(generatedQAs.AsAsyncQueryable());
        _embeddingModelRepositoryMock.Setup(r => r.GetByIdAsync(1))
            .ReturnsAsync(new EmbeddingModel { Id = 1, Name = "multilingual-e5-base" });
        _documentRepositoryMock.Setup(r => r.GetByCourseIdAsync(courseId))
            .ReturnsAsync(documents);
        _chunkRepositoryMock.Setup(r => r.GetChunksWithEmbeddingsByDocumentIdsAsync(It.IsAny<IList<int>>()))
            .ReturnsAsync(chunks);
        _embeddingServiceMock.Setup(s => s.GenerateEmbeddingAsync(It.IsAny<string>()))
            .ReturnsAsync(new[] { 1f, 0f, 0f });
        _llmServiceMock.Setup(s => s.GenerateAnswerAsync(It.IsAny<string>(), It.IsAny<string>()))
            .ReturnsAsync("Xin lỗi, đã xảy ra lỗi khi kết nối với AI (Gemini). Vui lòng thử lại sau.");

        var service = CreateService();

        await service.CreateAndRunBenchmarkAsync(new CreateBenchmarkRunDto
        {
            Name = "RAG with provider errors",
            EmbeddingModelId = 1,
            ChunkingStrategy = "FixedSize",
            ChunkSize = 512,

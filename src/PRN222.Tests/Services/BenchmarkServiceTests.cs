            result.Faithfulness == 0 &&
            result.AnswerRelevancy == 0)), Times.Once);
    }

    private BenchmarkService CreateService()
    {
        _embeddingServiceMock.SetupGet(s => s.ModelName).Returns("multilingual-e5-base");
        var embeddingServiceFactory = new EmbeddingServiceFactory(
            new[] { _embeddingServiceMock.Object },
            NullLogger<EmbeddingServiceFactory>.Instance);
        var ragRetrievalService = new RagRetrievalService(
            _documentRepositoryMock.Object,
            _chunkRepositoryMock.Object,
            new MemoryCache(new MemoryCacheOptions()),
            NullLogger<RagRetrievalService>.Instance);

        return new BenchmarkService(
            _runRepositoryMock.Object,
            _resultRepositoryMock.Object,
            _chunkEmbeddingRepositoryMock.Object,
            _qaPairRepositoryMock.Object,
            _chunkRepositoryMock.Object,
            _documentRepositoryMock.Object,
            _embeddingModelRepositoryMock.Object,
            _embeddingServiceMock.Object,
            embeddingServiceFactory,
            ragRetrievalService,
            _llmServiceMock.Object,
            _fineTunedModelServiceMock.Object,
            _unitOfWorkMock.Object,
            _loggerMock.Object);
    }
